Principal = 1000

rate = 7 / 100

n_1 = 10
n_2 = 20
n_3 = 30

Amount_of_deposit_after_10_years = Principal * (1 + rate) ** n_1

Amount_of_deposit_after_20_years = Principal * (1 + rate) ** n_2

Amount_of_deposit_after_30_years = Principal * (1 + rate) ** n_3


print("invested amount after 10 years is", round(Amount_of_deposit_after_10_years, 2))

print("invested amount after 20 years is", round(Amount_of_deposit_after_20_years, 2))

print("invested amount after 30 years is", round(Amount_of_deposit_after_30_years, 2))
